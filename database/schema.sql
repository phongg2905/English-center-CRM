-- Hàm tự động cập nhật trường updated_at mỗi khi có thao tác UPDATE
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Hàm tự động tính toán sĩ số thực tế (current_enrolled) & tự khóa lớp (status = 'FULL')
CREATE OR REPLACE FUNCTION sync_class_enrolled_count()
RETURNS TRIGGER AS $$
DECLARE
    target_class_id INT;
    actual_count INT;
    class_capacity INT;
BEGIN
    IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN
        target_class_id := NEW.class_id;
    ELSE
        target_class_id := OLD.class_id;
    END IF;

    -- Đếm sĩ số học viên thực tế đang học
    SELECT COUNT(*) INTO actual_count
    FROM enrollments
    WHERE class_id = target_class_id AND status = 'ENROLLED';

    -- Lấy sức chứa tối đa của lớp
    SELECT max_capacity INTO class_capacity
    FROM classes
    WHERE id = target_class_id;

    -- Cập nhật sĩ số vào bảng classes
    UPDATE classes
    SET current_enrolled = actual_count,
        status = CASE 
            WHEN actual_count >= class_capacity THEN 'FULL'
            WHEN status = 'FULL' AND actual_count < class_capacity THEN 'OPEN'
            ELSE status
        END,
        updated_at = CURRENT_TIMESTAMP
    WHERE id = target_class_id;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

