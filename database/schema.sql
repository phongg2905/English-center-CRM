    speaking_score NUMERIC(3,1) CHECK (speaking_score IS NULL OR (speaking_score >= 0.0 AND speaking_score <= 9.0)),
    overall_score NUMERIC(3,1) CHECK (overall_score IS NULL OR (overall_score >= 0.0 AND overall_score <= 9.0)),
    suggested_course_id INT REFERENCES courses(id) ON DELETE SET NULL,
