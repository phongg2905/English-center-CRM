-- 3.1. Bảng roles (Danh mục Vai trò Người dùng - RBAC)
CREATE TABLE roles (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(30) UNIQUE NOT NULL,
    role_name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_role_code CHECK (role_code IN ('ADMIN', 'SALES', 'ACADEMIC'))
);

CREATE TRIGGER trg_roles_updated_at 
BEFORE UPDATE ON roles 
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- 3.2. Bảng users (Tài khoản Nhân sự Trung tâm)
CREATE TABLE users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(120) UNIQUE NOT NULL,
    phone_number VARCHAR(20),
    role_id INT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    avatar_url VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_username_format CHECK (username ~ '^[a-zA-Z0-9_\.]+$')
);

CREATE TRIGGER trg_users_updated_at 
BEFORE UPDATE ON users 
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- 3.3. Bảng leads (Khách hàng Tiềm năng & Phễu Tuyển sinh)
CREATE TABLE leads (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    phone_number VARCHAR(20) UNIQUE NOT NULL,
    email VARCHAR(120),
    interest VARCHAR(50) NOT NULL,
    source_channel VARCHAR(50) NOT NULL,
    pipeline_stage VARCHAR(30) NOT NULL DEFAULT 'NEW',
    lost_reason VARCHAR(100),
    assigned_sales_id INT REFERENCES users(id) ON DELETE SET NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_leads_interest CHECK (interest IN ('IELTS', 'TOEIC', 'COMMUNICATION')),
    CONSTRAINT chk_leads_source CHECK (source_channel IN ('FB_ADS', 'WEBSITE', 'HOTLINE', 'WALK_IN', 'REFERRAL')),
    CONSTRAINT chk_leads_stage CHECK (pipeline_stage IN ('NEW', 'CONTACTING', 'TEST_SCHEDULED', 'ENROLLED', 'LOST'))
);

CREATE TRIGGER trg_leads_updated_at 
BEFORE UPDATE ON leads 
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- 3.4. Bảng interaction_logs (Nhật ký Tương tác & Lịch sử Chăm sóc Lead)
CREATE TABLE interaction_logs (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id INT NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
    user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    interaction_type VARCHAR(30) NOT NULL,
    potential_level VARCHAR(20) NOT NULL,
    content TEXT NOT NULL,
    next_follow_up_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_interaction_type CHECK (interaction_type IN ('PHONE_CALL', 'SMS', 'DIRECT_MEETING', 'SYSTEM_NOTE')),
    CONSTRAINT chk_potential_level CHECK (potential_level IN ('HOT', 'WARM', 'COLD'))
);

-- 3.5. Bảng courses (Danh mục Khóa học Đào tạo)
