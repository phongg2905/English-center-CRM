    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_test_type CHECK (test_type IN ('IELTS', 'TOEIC', 'GENERAL')),
    CONSTRAINT chk_attendance_status CHECK (attendance_status IN ('SCHEDULED', 'PRESENT', 'ABSENT', 'CANCELLED'))
