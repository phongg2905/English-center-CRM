    standard_tuition NUMERIC(12,2) NOT NULL CHECK (standard_tuition >= 0),
    min_entry_score NUMERIC(3,1) CHECK (min_entry_score >= 0.0 AND min_entry_score <= 9.0),
    max_entry_score NUMERIC(3,1) CHECK (max_entry_score >= 0.0 AND max_entry_score <= 9.0),
    target_output VARCHAR(100),
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TRIGGER trg_courses_updated_at 
BEFORE UPDATE ON courses 
FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- 3.6. Bảng placement_tests (Lịch hẹn & Kết quả Đánh giá Trình độ Đầu vào)
