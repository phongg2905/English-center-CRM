    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_student_class UNIQUE(student_id, class_id),
    CONSTRAINT chk_enrollment_payment_status CHECK (payment_status IN ('UNPAID', 'PARTIAL', 'FULLY_PAID')),
    CONSTRAINT chk_enrollment_status CHECK (status IN ('ENROLLED', 'TRANSFERRED', 'DROPPED', 'COMPLETED'))
