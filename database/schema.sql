-- 5. CÁC DATABASE VIEWS HỖ TRỢ BÁO CÁO & FRONTEND DASHBOARD
-- ==============================================================================
CREATE OR REPLACE VIEW v_classes_summary AS
SELECT 
    c.id AS class_id,
    c.class_code,
    c.class_name,
    co.course_name,
    c.schedule_days,
    c.time_slot,
    c.room,
    c.teacher_name,
    c.start_date,
    c.max_capacity,
    c.current_enrolled,
    (c.max_capacity - c.current_enrolled) AS remaining_slots,
    ROUND((c.current_enrolled::NUMERIC / c.max_capacity::NUMERIC) * 100, 1) AS occupancy_rate,
    c.status
FROM classes c
JOIN courses co ON c.course_id = co.id;

CREATE OR REPLACE VIEW v_leads_kanban AS
SELECT 
    l.id AS lead_id,
    l.full_name,
    l.phone_number,
    l.email,
    l.interest,
    l.source_channel,
    l.pipeline_stage,
    l.lost_reason,
    u.full_name AS assigned_sales_name,
    l.created_at,
    (SELECT MAX(created_at) FROM interaction_logs WHERE lead_id = l.id) AS last_contacted_at,
    (SELECT COUNT(*) FROM interaction_logs WHERE lead_id = l.id) AS total_interactions
FROM leads l
LEFT JOIN users u ON l.assigned_sales_id = u.id;

CREATE OR REPLACE VIEW v_sales_kpi_dashboard AS
SELECT 
    u.id AS sales_id,
    u.full_name AS sales_name,
    COUNT(DISTINCT l.id) AS total_assigned_leads,
    COUNT(DISTINCT CASE WHEN l.pipeline_stage = 'ENROLLED' THEN l.id END) AS converted_students,
    ROUND(
        CASE 
            WHEN COUNT(DISTINCT l.id) = 0 THEN 0 
            ELSE (COUNT(DISTINCT CASE WHEN l.pipeline_stage = 'ENROLLED' THEN l.id END)::NUMERIC / COUNT(DISTINCT l.id)::NUMERIC) * 100 
        END, 1
    ) AS conversion_rate,
    COALESCE(SUM(pr.amount), 0) AS total_revenue_collected
FROM users u
LEFT JOIN leads l ON u.id = l.assigned_sales_id
LEFT JOIN enrollments e ON u.id = e.consultant_id
LEFT JOIN payment_receipts pr ON e.id = pr.enrollment_id
JOIN roles r ON u.role_id = r.id
WHERE r.role_code = 'SALES'
GROUP BY u.id, u.full_name;
